#!/usr/bin/env python3
#Tessera-8 ISA

REGS = {"A": 0, "B": 1, "H": 2, "L": 3}

PC_RESET = 0x0000
SP_RESET = 0x01FF
SRAM_END = 0x01FF
UART_DATA, UART_STATUS = 0xFF00, 0xFF01
GPIO_OUT, GPIO_IN = 0xFF02, 0xFF03
CYCLES_LO, CYCLES_HI = 0xFF04, 0xFF05

# name -> (opcode, total length in bytes, operand)
# operand: None, "imm8" (one byte after the opcode), "abs16" (two bytes, little endian)

FIXED = {
    "NOP": (0x00, 1, None),  "HLT": (0x01, 1, None),
    # ALU
    "ADD": (0x20, 1, None),  "SUB": (0x21, 1, None),  "AND": (0x22, 1, None),
    "OR":  (0x23, 1, None),  "XOR": (0x24, 1, None),  "CMP": (0x25, 1, None),
    "ADDI": (0x28, 2, "imm8"), "CMPI": (0x29, 2, "imm8"),
    "ADC": (0x26, 1, None),  "SBC": (0x27, 1, None),
    # operations on A
    "INC_A": (0x30, 1, None), "DEC_A": (0x31, 1, None), "NOT_A": (0x32, 1, None),
    "SHL_A": (0x33, 1, None), "SHR_A": (0x34, 1, None),
    "NEG_A": (0x35, 1, None), "SAR_A": (0x36, 1, None),
    # mul/div
    "MUL": (0x38, 1, None),  "DIV": (0x39, 1, None),
    # memory
    "LD_ABS": (0x50, 3, "abs16"), "ST_ABS": (0x51, 3, "abs16"),
    "LD_HL": (0x52, 1, None),     "ST_HL": (0x53, 1, None),
    "INC_HL": (0x54, 1, None),    "DEC_HL": (0x55, 1, None),
    # stack and calls
    "PUSH_A": (0x58, 1, None), "POP_A": (0x59, 1, None),
    "CALL": (0x5A, 3, "abs16"), "RET": (0x5B, 1, None),
    # jumps
    "JMP": (0x60, 3, "abs16"), "JZ":  (0x61, 3, "abs16"), "JNZ": (0x62, 3, "abs16"),
    "JC":  (0x63, 3, "abs16"), "JNC": (0x64, 3, "abs16"),
    "JLT": (0x65, 3, "abs16"), "JGE": (0x66, 3, "abs16"),
}

LDI_BASE = 0x10   # LDI r,imm8  -> opcode LDI_BASE + r              (0x10-0x13), 2 bytes
MOV_BASE = 0x40   # MOV rd,rs   -> opcode MOV_BASE + rd*4 + rs      (0x40-0x4F), 1 byte

# opcode -> (mnemonic, length, operand, register fields)
DECODE = {}
for name, (op, length, kind) in FIXED.items():
    assert op not in DECODE, f"duplicate opcode {op:#04x} ({name})"
    DECODE[op] = (name, length, kind, ())
for r in range(4):
    op = LDI_BASE + r
    assert op not in DECODE
    DECODE[op] = ("LDI", 2, "imm8", (r,))
for rd in range(4):
    for rs in range(4):
        op = MOV_BASE + rd * 4 + rs
        assert op not in DECODE
        DECODE[op] = ("MOV", 1, None, (rd, rs))

def verilog_header():
    out = ["// Generated by tools/isa.py. Do not edit by hand."]
    for name, (op, _, _) in FIXED.items():
        out.append(f"localparam [7:0] OP_{name} = 8'h{op:02X};")
    out.append(f"localparam [7:0] OP_LDI_BASE = 8'h{LDI_BASE:02X};")
    out.append(f"localparam [7:0] OP_MOV_BASE = 8'h{MOV_BASE:02X};")
    return "\n".join(out)

if __name__ == "__main__":
    import sys
    if "--vh" in sys.argv:
        print(verilog_header())
    else:
        print(f"ISA: {len(DECODE)} opcode values")